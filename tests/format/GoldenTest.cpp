TEST(GoldenTest, AnsPayloadBytesAreStable) {
  const auto codec = CodecRegistry::instance().create("ans");
  ASSERT_NE(codec, nullptr);
  EXPECT_EQ(codec->compress(sampleInput()), fromHex(kAnsPayloadHex));
}

