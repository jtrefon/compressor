TEST(GoldenTest, CproAnsFixtureHeaderFields) {
  const format::FileHeader header =
      format::deserializeHeader(fromHex(kCproAnsFrameHex));
  EXPECT_EQ(header.formatVersion, format::FORMAT_VERSION);
  EXPECT_EQ(header.algorithmId, format::AlgorithmID::ANS_COMPRESSOR);
  EXPECT_EQ(header.originalSize, 19u);
  EXPECT_EQ(header.originalChecksum,
            utils::crc32Calculator.calculate(sampleInput()));
  EXPECT_EQ(header.chunkCount, 1u);
  EXPECT_EQ(header.chunkSize, 19u);
  ASSERT_EQ(header.compressedSizes.size(), 1u);
  EXPECT_EQ(header.compressedSizes[0], 536u);
}

